"""Tests for --stats folder statistics (read-only, needs ffprobe)."""

import shutil
import subprocess
import sys
from pathlib import Path

import pytest

from nightcore.cli import main
from nightcore.stats import collect_stats, is_truly_lossless, render_stats


def _require_tools(*names):
    missing = [n for n in names if shutil.which(n) is None]
    if missing:
        pytest.skip("missing tools for stats tests: " + ", ".join(missing))


def _sine_flac(path, seconds=1):
    subprocess.run(
        ["ffmpeg", "-y", "-v", "error", "-f", "lavfi", "-i",
         f"sine=frequency=440:duration={seconds}",
         "-c:a", "flac", str(path)],
        check=True,
    )


def _run(monkeypatch, capsys, argv):
    monkeypatch.setattr(sys, "argv", ["nightcore", *argv])
    rc = main()
    out = capsys.readouterr()
    return rc, out.out, out.err


def test_is_truly_lossless_strict():
    assert is_truly_lossless("flac") is True
    assert is_truly_lossless("mp3") is False
    # Lossless container, lossy past: not truly lossless.
    assert is_truly_lossless("flac", origin_codec="mp3") is False
    assert is_truly_lossless("flac", filename_codec="mp3") is False
    assert is_truly_lossless("flac", origin_codec="flac") is True
    assert is_truly_lossless("pcm_s16le") is True


def test_collect_stats_folder(tmp_path):
    _require_tools("ffmpeg", "ffprobe")
    _sine_flac(tmp_path / "song [1.2x].flac")
    _sine_flac(tmp_path / "song2 [1.25x].flac")
    _sine_flac(tmp_path / "plain.flac")
    (tmp_path / "song [1.2x].lrc").write_text("[00:01.00]hi\n")
    sub = tmp_path / "sub"
    sub.mkdir()
    _sine_flac(sub / "nested.flac")
    (tmp_path / "notes.txt").write_text("not audio\n")

    data = collect_stats(tmp_path)
    assert len(data["audio"]) == 3  # depth 1 only: nested/ ignored
    assert len(data["lrc_files"]) == 1
    assert data["unreadable"] == []
    # Threaded probing keeps the sorted input order deterministic.
    assert [r["name"] for r in data["audio"]] == sorted(
        r["name"] for r in data["audio"])

    speeds = sorted(r["speed"] for r in data["audio"])
    assert speeds == [1.0, 1.2, 1.25]
    assert all(r["shift_source"] == "filename"
               for r in data["audio"] if r["speed"] != 1.0)
    assert all(r["lossless"] for r in data["audio"])

    text = "\n".join(render_stats(data))
    assert "3 audio file(s)" in text
    assert "average 1.15x" in text
    assert "median 1.2x" in text
    assert "1.2x : 1" in text and "1.25x: 1" in text
    assert "1 of 3 audio file(s) have" in text
    assert "3 truly lossless" in text
    assert "Generated by nightcore.py @" in text


def test_stats_cli_end_to_end(monkeypatch, capsys, tmp_path):
    _require_tools("ffmpeg", "ffprobe")
    _sine_flac(tmp_path / "a [1.2x].flac")
    _sine_flac(tmp_path / "b.flac")
    rc, out, _ = _run(monkeypatch, capsys, ["--stats", str(tmp_path)])
    assert rc == 0
    assert "2 audio file(s)" in out
    assert "average 1.1x" in out
    assert "Generated by nightcore.py @" in out


def test_stats_cli_errors(monkeypatch, capsys, tmp_path):
    _require_tools("ffprobe")
    rc, _, _ = _run(monkeypatch, capsys,
                     ["--stats", str(tmp_path / "missing")])
    assert rc == 1
    empty = tmp_path / "empty"
    empty.mkdir()
    rc, _, _ = _run(monkeypatch, capsys, ["--stats", str(empty)])
    assert rc == 1
    _require_tools("ffmpeg")
    _sine_flac(tmp_path / "a.flac")
    rc, _, _ = _run(monkeypatch, capsys,
                     ["--stats", str(tmp_path), str(tmp_path / "a.flac")])
    assert rc == 1
    rc, _, _ = _run(monkeypatch, capsys,
                     ["--stats", str(tmp_path), "--batch", str(tmp_path)])
    assert rc == 1
    rc, _, _ = _run(monkeypatch, capsys,
                     ["--stats", str(tmp_path), "-s", "1.2"])
    assert rc == 1


def test_stats_ignores_corrupt_file(monkeypatch, capsys, tmp_path):
    _require_tools("ffmpeg", "ffprobe")
    _sine_flac(tmp_path / "good.flac")
    (tmp_path / "broken.flac").write_bytes(b"not audio at all")
    data = collect_stats(tmp_path)
    assert len(data["audio"]) == 1
    assert data["unreadable"] == ["broken.flac"]
    rc, out, _ = _run(monkeypatch, capsys, ["--stats", str(tmp_path)])
    assert rc == 0
    assert "1 audio file(s)" in out
    assert "1 unreadable" in out


class _FakeTty:
    """Capture-only stderr stand-in reporting itself as a TTY."""

    def __init__(self):
        self.chunks = []

    def isatty(self):
        return True

    def write(self, s):
        self.chunks.append(s)

    def flush(self):
        pass

    @property
    def text(self):
        return "".join(self.chunks)


def test_progress_silent_when_redirected(monkeypatch, capsys, tmp_path):
    # Under pytest stderr is not a TTY (like `> file` / `2> file`):
    # progress must stay silent even when asked for.
    _require_tools("ffmpeg", "ffprobe")
    _sine_flac(tmp_path / "a.flac")
    assert not sys.stderr.isatty()
    data = collect_stats(tmp_path, progress=True)
    assert len(data["audio"]) == 1
    captured = capsys.readouterr()
    assert captured.err == ""


def test_progress_tty_rewrites_one_line(monkeypatch, tmp_path):
    from nightcore import stats as stats_mod
    _require_tools("ffmpeg", "ffprobe")
    _sine_flac(tmp_path / "a.flac")
    _sine_flac(tmp_path / "b.flac")
    fake = _FakeTty()
    monkeypatch.setattr(sys, "stderr", fake)
    data = collect_stats(tmp_path, progress=True)
    assert len(data["audio"]) == 2
    assert "\r" in fake.text  # carriage-return rewrites ...
    assert "\n" not in fake.text  # ... never newlines ...
    assert fake.text.endswith("\r")  # ... and the line is erased at the end


def test_progress_suppressed_by_qq(monkeypatch, tmp_path):
    from nightcore import stats as stats_mod
