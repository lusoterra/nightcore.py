def _pack(tmp_path):
    # Artist/Album layout: top.flac (1) + Artist/Album/*.flac (2).
    _sine_flac(tmp_path / "top [1.2x].flac")
    album = tmp_path / "Artist" / "Album"
    album.mkdir(parents=True)
    _sine_flac(album / "one [1.2x].flac")
    _sine_flac(album / "two [1.25x].flac")
    (album / "one [1.2x].lrc").write_text("[00:01.00]hi\n")
    (tmp_path / "stray.lrc").write_text("[00:01.00]no audio here\n")
    return album


def test_recurse_depth_limit(monkeypatch, capsys, tmp_path):
    _require_tools("ffmpeg", "ffprobe")
    _pack(tmp_path)
    rc, out, _ = _run(monkeypatch, capsys, ["--stats", str(tmp_path)])
    assert rc == 0
    assert "1 audio file(s)" in out and "(depth 1)" in out
    assert "0 of 1 audio file(s) have" in out  # stray.lrc pairs nowhere

    rc, out, _ = _run(monkeypatch, capsys,
                       ["--stats", str(tmp_path), "--recurse", "2"])
    assert rc == 0
    assert "depth <= 2" in out
    assert "1 audio file(s)" in out  # level 2 is Artist/, still no audio

    rc, out, _ = _run(monkeypatch, capsys,
                       ["--stats", str(tmp_path), "--recurse"])
    assert rc == 0
    assert "recursive, everything" in out
    assert "3 audio file(s) in 2 dir(s)" in out
    # Lyrics pair per directory: the Album .lrc counts once, stray never.
    assert "1 of 3 audio file(s) have" in out
    assert "Folders:" in out and "Artist/Album: 2" in out
    assert "1.2x : 2" in out  # bars on the speed rows


def test_recurse_flag_errors(monkeypatch, capsys, tmp_path):
    _require_tools("ffmpeg", "ffprobe")
    _sine_flac(tmp_path / "a.flac")
    rc, _, _ = _run(monkeypatch, capsys, ["--recurse"])
    assert rc == 1
    rc, _, _ = _run(monkeypatch, capsys,
                     ["--stats", str(tmp_path), "--recurse", "0"])
    assert rc == 1
    rc, out, _ = _run(monkeypatch, capsys,
                       ["--stats", str(tmp_path), "--recurse", "5"])
    assert rc == 0
    assert "depth <= 5" in out


def test_speed_rows_align():
    # Keys, counts and bars share columns regardless of width.
    from nightcore.stats import render_stats

    def _rec(speed):
        return {"name": "x.flac", "d": ".", "codec": "flac",
                "bit_rate": 800000, "bits": 16, "sample_rate": 44100,
                "speed": speed, "st": 0.0, "shift_source": "none",
                "origin_codec": None, "filename_codec": None,
                "lossless": True, "resampled": False,
                "denightcored": False, "lyrics": False}

    data = {"dir": ".", "max_depth": 1,
            "audio": [_rec(1.2), _rec(1.2), _rec(1.25), _rec(1.0)],
            "lrc_files": [], "unreadable": []}
    rows = [ln for ln in render_stats(data) if "█" in ln]
    assert len(rows) == 3
    assert len({ln.index("█") for ln in rows}) == 1


def test_progress_never_wraps(monkeypatch):
    # A narrow stderr terminal must truncate, never wrap: every
    # carriage-return segment stays within the measured width, so the
    # final clear erases the line exactly (no residue like the
    # "Remix).flac" tail once seen on a wide-stdout/narrow-stderr box).
    from nightcore import stats as stats_mod
    fake = _FakeTty()
    monkeypatch.setattr(sys, "stderr", fake)
    monkeypatch.setattr(stats_mod, "_term_width", lambda: 30)
    width = 0
    for name in ("short.flac",
                 "a much longer song name (Spedycake Remix).flac",
                 "mid.flac"):
        width = stats_mod._progress_tick(1, 3, name, width)
    stats_mod._progress_clear(width)
    for segment in fake.text.split("\r"):
        assert len(segment) <= 30
    assert "\n" not in fake.text
